"""Bundle the exported stimuli into a browser-loadable JS file for the jsPsych experiment.
Run (after export_stimuli.py):  python study/experiment/build_stimuli_js.py
Writes: study/experiment/stimuli.js  ->  window.STIMULI = {beer:[...], amzbook:[...]}
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
STIM = os.path.join(os.path.dirname(HERE), "stimuli")

bundle = {}
for dom in ("beer", "amzbook"):
    bundle[dom] = json.load(open(os.path.join(STIM, f"stimuli_{dom}.json"), encoding="utf-8"))

out = os.path.join(HERE, "stimuli.js")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Auto-generated by build_stimuli_js.py — do not edit by hand.\n")
    f.write("window.STIMULI = ")
    json.dump(bundle, f, ensure_ascii=False)
    f.write(";\n")
print(f"wrote {out}  (beer: {len(bundle['beer']['main'])}+{len(bundle['beer']['escalation'])}, "
      f"amzbook: {len(bundle['amzbook']['main'])}+{len(bundle['amzbook']['escalation'])} main+escalation)")
